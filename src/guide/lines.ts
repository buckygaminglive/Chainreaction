/** The words as the bubble shows them: direction tags removed. */
export function displayText(line: string): string {
  return line.replace(/\[[^\]]*\]\s*/g, '').trim();
}

export function audioPath(category: LineCategory, index: number): string {
  return `/audio/nova/${category}-${String(index + 1).padStart(2, '0')}.mp3`;
}
